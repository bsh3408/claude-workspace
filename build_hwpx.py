CELL = d.ensure_run_style(font="휴먼명조", size=10)


def last():
    return len(d.paragraphs) - 1


def para(text, style=BODY, align=None, left=0.0, hang=0.0, before=0, after=3):
    d.add_paragraph(text, char_pr_id_ref=style)
    d.set_paragraph_format(
        paragraph_index=last(), alignment=align, line_spacing_percent=160,
        indent_left_mm=left, first_line_indent_mm=-hang if hang else 0,
        spacing_before_pt=before, spacing_after_pt=after,
    )


def sq(text):  # □ 1단계
    para("□ " + text, BOLD, left=0, before=4)


def ci(text):  # ○ 2단계
    para("○ " + text, left=5, hang=4)


def da(text):  # - 3단계
    para("- " + text, left=10, hang=3)


def heading(text):
    para(text, H1, before=12, after=4)


def table(rows, widths, shade_first_col=False):
    t = d.add_table(len(rows), len(rows[0]), char_pr_id_ref=CELL)
    t.set_column_widths(widths)
    for r, row in enumerate(rows):
        for c, txt in enumerate(row):
            t.set_cell_text(r, c, txt)
            if r == 0:
                t.set_cell_shading(r, c, "#D9E2F3")
            elif shade_first_col and c == 0:
                t.set_cell_shading(r, c, "#F2F2F2")
    para("", after=2)


